import { describe, expect, it } from 'vitest'
import { plural } from './plural'

const notes: [string, string, string] = ['запись', 'записи', 'записей']

describe('склонение по числу', () => {
  it('один, несколько, много', () => {
    expect([0, 1, 2, 3, 4, 5, 9, 10].map((n) => plural(n, notes))).toEqual([
      'записей',
      'запись',
      'записи',
      'записи',
      'записи',
      'записей',
      'записей',
      'записей',
    ])
  })

  it('от 11 до 19 всегда много', () => {
    for (let n = 11; n <= 19; n++) expect(plural(n, notes)).toBe('записей')
  })

  it('после двадцати снова по последней цифре', () => {
    expect([21, 22, 25, 31, 101, 111, 112, 121, 1002].map((n) => plural(n, notes))).toEqual([
      'запись',
      'записи',
      'записей',
      'запись',
      'запись',
      'записей',
      'записей',
      'запись',
      'записи',
    ])
  })

  it('отрицательные числа ведут себя как положительные', () => {
    expect(plural(-1, notes)).toBe('запись')
    expect(plural(-5, notes)).toBe('записей')
  })
})
